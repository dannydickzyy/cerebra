"""Package editable HTML fragments for the static Streamlit component.

Run ``python -m cerebra.frontend`` after changing frontend/templates/*.html.
The Streamlit host also refreshes this bundle before serving the component.
"""
import json
import re
from pathlib import Path

FRONTEND = Path(__file__).resolve().parents[1] / "frontend"


def build_templates():
    """Write only when the source changes, avoiding unnecessary browser reloads."""
    templates = {}
    for source in sorted((FRONTEND / "templates").glob("*.html")):
        for name, markup in re.findall(
            r'<template id="([\w-]+)">\s*([\s\S]*?)\s*</template>',
            source.read_text(encoding="utf-8"),
        ):
            if name in templates:
                raise ValueError(f"Duplicate frontend template: {name}")
            templates[name] = markup
    if not templates:
        raise ValueError("No frontend templates found")
    bundle = (
        "// Generated by python -m cerebra.frontend. Edit templates/*.html instead.\n"
        '"use strict";\nconst pageTemplates = '
        + json.dumps(templates, ensure_ascii=False, indent=2)
        + ";\n"
    )
    target = FRONTEND / "static" / "js" / "templates.generated.js"
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists() or target.read_text(encoding="utf-8") != bundle:
        target.write_text(bundle, encoding="utf-8")


if __name__ == "__main__":
    build_templates()
